#!/usr/bin/env node
/**
 * @file Build the renderer's ES module directories into classic scripts.
 */
// The renderer is 300 classic scripts sharing one global scope, loaded in
// index.html's order and concatenated by bundle-renderer.mjs. Moving it to
// ES modules one directory at a time needs a bridge: a directory written as
// modules, built here with esbuild into ONE classic file under
// core/generated/ that defines a global (`var <global> = ...`). index.html,
// the offline exporter and the bundler then treat that file like any other
// script, and classic code reaches the module through the global. When the
// last classic script has moved, this step becomes the bundle itself.
//
//   node scripts/build/bundle-modules.mjs            build every module
//   node scripts/build/bundle-modules.mjs --check    build in memory and fail
//                                                    if a checked-in file is
//                                                    stale (the test runs this)
//
// The list is scripts/build/modules.json. The output is formatted with the
// repo's prettier so the format gate accepts it, and carries a header naming
// its source: the file is committed (dev loads index.html unbundled, and the
// deploy's bundle step reads the committed tree) and rebuilt by npm run build.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import prettier from 'prettier';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = join(ROOT, 'app/renderer');
const CHECK = process.argv.includes('--check');
const manifest = JSON.parse(
  readFileSync(join(ROOT, 'scripts/build/modules.json'), 'utf8')
);

let stale = 0;
for (const m of manifest.modules) {
  const r = await build({
    entryPoints: [join(SRC, m.entry)],
    bundle: true,
    format: 'iife',
    globalName: m.global,
    target: 'es2022',
    write: false,
    legalComments: 'none',
    logLevel: 'silent',
  });
  const header =
    `// GENERATED by scripts/build/bundle-modules.mjs from ${m.entry} -- do not edit by hand.\n` +
    `// Rebuilt by npm run build; tools/verify/test_modules_built.js checks it is current.\n` +
    `/* exported ${m.global} */\n`;
  const code = await prettier.format(header + r.outputFiles[0].text, {
    filepath: join(SRC, m.out),
  });
  const out = join(SRC, m.out);
  let have = null;
  try {
    have = readFileSync(out, 'utf8');
  } catch {
    /* not built yet */
  }
  if (CHECK) {
    if (have !== code) {
      stale++;
      console.error(
        `bundle-modules: ${m.out} is stale (rebuild with npm run build)`
      );
    }
  } else if (have !== code) {
    writeFileSync(out, code);
    console.log(`bundle-modules: ${m.entry} -> ${m.out} (${code.length} B)`);
  }
}
if (CHECK) {
  if (stale) process.exit(1);
  console.log(`bundle-modules: ${manifest.modules.length} module(s) current`);
}
