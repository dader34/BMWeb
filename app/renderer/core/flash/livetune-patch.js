// Flashing/Tuning: live tune put on a DME from the pair BMWeb has loaded --
// "Install live tune" in Custom Options. BENCH ONLY (localhost).
//
// Live tune (ms45-emu docs/livetune-design.md) is four patches on the stock
// 0044570 program: the RAM overlay that redirects table reads into SRAM
// mirrors, the transport on the 2C define-packet handler, the fold that
// saves the open tables into the calibration (at key-off, when asked), and
// the single values made live. All of it is independent of the tune but
// for one thing: the fold keeps a GOLDEN copy of the calibration at ext
// 0xE0000, which a save rebuilds the calibration from. So the patch is
// fixed bytes (livetune-blob.js, generated by ms45-emu tools/livetune_js.py)
// plus that copy, taken here from the pair's own calibration exactly as the
// program flash will write it.
//
// The blob's footprint covers every byte any live tune build on the stock
// program touches, with live tune 7's bytes there (stock where 7 leaves a
// byte alone). The splice first checks that the pair's bytes over it are
// the stock program's or one of those builds' (a CRC each), so laying 7
// down installs it on a stock program and upgrades an older build in
// place; anything else -- another program, or an edit of the app's own
// sitting in the footprint -- is refused before anything is sent.
//
// The program CRCs and the signature are redone by every program flash;
// the safety monitor's ROM-test sum, which live tune's hooks fall inside,
// is redone here, so the splice has to be the last thing done to the pair.
/* exported liveTunePatch */

const LT_FLASH_LENGTH = 0x100000;
const LT_MPC_LENGTH = 0x70000;
const LT_CAL_START = 0x40000;
const LT_CAL_LENGTH = 0x1d000;
const LT_CAL_MARKS = 0x5ff80; // the loader's valid marks: the end of the cal sector
const LT_ROMTEST_SUM = 0x60600;
const LT_ROMTEST_RANGES = 0x60608;
const LT_ROMTEST_SEED = 0x0123456789abcdefn;
const LT_EXT = 0xfff00000;

const ltData =
  typeof liveTuneBlob !== 'undefined'
    ? liveTuneBlob
    : require('./livetune-blob.js').liveTuneBlob;
const ltChecksums =
  typeof ms45Checksums !== 'undefined'
    ? ms45Checksums
    : require('../ms45/ms45.js').ms45Checksums;

/** @param {string} hex @returns {Uint8Array} */
function _ltHex(hex) {
  const out = new Uint8Array(hex.length / 2);
  for (let i = 0; i < out.length; i++)
    out[i] = parseInt(hex.substr(i * 2, 2), 16);
  return out;
}

/** @param {Uint8Array} b @param {number} at @returns {number} */
function _ltBe32(b, at) {
  return (
    ((b[at] << 24) | (b[at + 1] << 16) | (b[at + 2] << 8) | b[at + 3]) >>> 0
  );
}

/** CRC-32 as zlib computes it (the blob's `known`). */
function _ltCrc32(chunks) {
  let crc = 0xffffffff;
  for (const b of chunks)
    for (let i = 0; i < b.length; i++) {
      crc ^= b[i];
      for (let k = 0; k < 8; k++) crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1));
    }
  return (crc ^ 0xffffffff) >>> 0;
}

/** The footprint as [offset, bytes] runs, decoded once. */
let _ltRuns = null;
function _ltFootprint() {
  if (!_ltRuns)
    _ltRuns = {
      ext: ltData.ext.map(([at, hex]) => [at, _ltHex(hex)]),
      mpc: ltData.mpc.map(([at, hex]) => [at, _ltHex(hex)]),
    };
  return _ltRuns;
}

/**
 * What the pair holds where live tune goes: 'stock', the name of a live
 * tune build (e.g. 'livetune6-notraps', 'livetune7'), or null.
 * @param {Uint8Array} flash - The 1 MB external image.
 * @param {Uint8Array} mpc - The 448 KB MPC image.
 * @returns {string|null}
 */
function liveTuneSurvey(flash, mpc) {
  if (flash.length !== LT_FLASH_LENGTH || mpc.length !== LT_MPC_LENGTH)
    return null;
  const fp = _ltFootprint();
  const crc = _ltCrc32([
    ...fp.ext.map(([at, b]) => flash.subarray(at, at + b.length)),
    ...fp.mpc.map(([at, b]) => mpc.subarray(at, at + b.length)),
  ]);
  for (const [name, v] of Object.entries(ltData.known))
    if (v === crc) return name;
  return null;
}

/** The safety monitor's 64-bit sum over the three ranges the program lists. */
function _ltRomTestSum(flash, mpc) {
  let total = LT_ROMTEST_SEED;
  for (let i = 0; i < 3; i++) {
    const start = _ltBe32(flash, LT_ROMTEST_RANGES + 8 * i);
    const end = _ltBe32(flash, LT_ROMTEST_RANGES + 8 * i + 4);
    const img = start < LT_EXT ? mpc : flash;
    const base = start < LT_EXT ? 0 : LT_EXT;
    for (let a = start; a < end; a += 4)
      total = (total + BigInt(_ltBe32(img, a - base))) & 0xffffffffffffffffn;
  }
  return total;
}

/** The fold's monitor sum of a calibration: 8 bytes, big-endian. */
function _ltMonitorSum(cal) {
  const m = ltData.monitor;
  let total = LT_ROMTEST_SEED;
  for (let a = m.from; a < m.to; a += 4)
    total = (total + BigInt(_ltBe32(cal, a))) & 0xffffffffffffffffn;
  const out = new Uint8Array(8);
  for (let i = 7; i >= 0; i--) {
    out[i] = Number(total & 0xffn);
    total >>= 8n;
  }
  return out;
}

/**
 * The pair with live tune 7 in it. Refuses (throws, nothing changed) a pair
 * whose program is not the stock one or a known live tune build over the
 * footprint, or whose calibration a save could not keep in step.
 * @param {Uint8Array} flash - The 1 MB external image, every other edit made.
 * @param {Uint8Array} mpc - The 448 KB MPC image.
 * @returns {{flash: Uint8Array, mpc: Uint8Array, from: string}}
 */
function liveTuneSplice(flash, mpc) {
  const from = liveTuneSurvey(flash, mpc);
  if (!from)
    throw new Error(
      'The loaded program is not the stock 0044570 program (or a live tune build of it) where live tune goes: another program, or an edit such as a protection in the same place. Nothing was written.'
    );
  const f = Uint8Array.from(flash);
  const m = Uint8Array.from(mpc);
  // the calibration as the program flash will write it: the golden copy
  // has to be those bytes, or the first save would carry the difference
  const cal = ltChecksums.signParameters(
    ltChecksums.correctParameterChecksums(
      f.slice(LT_CAL_START, LT_CAL_START + LT_CAL_LENGTH)
    )
  );
  const gl = ltData.goldLength;
  if (
    cal.subarray(gl).some((x) => x !== 0xff) ||
    f
      .subarray(LT_CAL_START + LT_CAL_LENGTH, LT_CAL_MARKS)
      .some((x) => x !== 0xff)
  )
    throw new Error(
      `The tune has data past calibration offset 0x${gl.toString(16)}, which a live tune save would not keep. Nothing was written.`
    );
  const mon = ltData.monitor;
  const want = _ltMonitorSum(cal);
  if (cal.subarray(mon.at, mon.at + 8).some((x, i) => x !== want[i]))
    throw new Error(
      "The tune's safety-monitor sum is not right, so a live tune save could not keep it in step. Nothing was written."
    );
  if (
    _ltBe32(f, mon.table) !== (0xffe40000 + mon.from) >>> 0 ||
    _ltBe32(f, mon.table + 4) !== (0xffe40000 + mon.to) >>> 0
  )
    throw new Error(
      'The safety monitor does not sum the range a live tune save keeps in step. Nothing was written.'
    );
  const room = f.subarray(ltData.goldAt, ltData.goldAt + gl);
  if (
    room.some((x) => x !== 0xff) &&
    room.subarray(0, 0x40).some((x, i) => x !== cal[i])
  )
    throw new Error(
      `ext 0x${ltData.goldAt.toString(16)} holds neither a calibration copy nor nothing. Nothing was written.`
    );
  const fp = _ltFootprint();
  for (const [at, b] of fp.ext) f.set(b, at);
  for (const [at, b] of fp.mpc) m.set(b, at);
  f.set(cal, LT_CAL_START);
  f.set(cal.subarray(0, gl), ltData.goldAt);
  let sum = _ltRomTestSum(f, m);
  for (let i = 7; i >= 0; i--) {
    f[LT_ROMTEST_SUM + i] = Number(sum & 0xffn);
    sum >>= 8n;
  }
  return { flash: f, mpc: m, from };
}

const liveTunePatch = {
  VERSION: ltData.version,
  NAME: ltData.name,
  survey: liveTuneSurvey,
  splice: liveTuneSplice,
  /** A survey result as words: 'the stock program', 'live tune 6 (no traps)'. */
  describe(from) {
    if (from === 'stock') return 'the stock program';
    const m = /^livetune(\d+)(-notraps)?$/.exec(from || '');
    return m ? `live tune ${m[1]}${m[2] ? ' (no traps)' : ''}` : 'unknown';
  },
};

if (typeof window !== 'undefined') window.liveTunePatch = liveTunePatch;
if (typeof module !== 'undefined' && module.exports)
  module.exports = { liveTunePatch };
